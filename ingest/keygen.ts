// Generates the two Ed25519 signing key pairs:
//   listings   signs listings.json. Only the listings updater (ingest) holds the private key.
//   directory  signs pros.json (advertiser directory). Only the web server holds the private key.
// Keeping them separate means a compromised web server can't publish fake listings.
//
// Private keys -> ingest/.keys/feed-signing.pem and ingest/.keys/directory-signing.pem (gitignored;
//                 store them in a secret manager in production).
// Public keys  -> src/feed/publicKey.ts (compiled into the site; the browser verifies with them), and
//                 ingest/.keys/feed-public-key.txt (the web server reads listings with it).
// With --print, all four are printed instead (for container builds; see README, Deploy).

import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateSigningKeys } from './lib/sign';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const KEY_DIR = join(ROOT, 'ingest', '.keys');
const feedFile = join(KEY_DIR, 'feed-signing.pem');
const directoryFile = join(KEY_DIR, 'directory-signing.pem');

const feed = generateSigningKeys();
const directory = generateSigningKeys();

// --print: for container deployments. Prints the keys instead of writing files: the public keys go into
// the image build (build arguments), the private keys into two separate secrets.
if (process.argv.includes('--print')) {
  console.log(
    `FEED_PUBLIC_KEY (build argument, safe to share):\n${feed.publicSpkiB64}\n\n` +
      `DIRECTORY_PUBLIC_KEY (build argument, safe to share):\n${directory.publicSpkiB64}\n\n` +
      `FEED_SIGNING_KEY (secret for the listings updater only, keep private):\n${feed.privatePem}\n` +
      `DIRECTORY_SIGNING_KEY (secret for the web server only, keep private):\n${directory.privatePem}`,
  );
  process.exit(0);
}

if ((existsSync(feedFile) || existsSync(directoryFile)) && !process.argv.includes('--rotate')) {
  console.error(`Signing keys already exist in ${KEY_DIR}. Pass --rotate to replace them (the site must be rebuilt afterwards).`);
  process.exit(1);
}
mkdirSync(KEY_DIR, { recursive: true, mode: 0o700 });
writeFileSync(feedFile, feed.privatePem, { mode: 0o600 });
writeFileSync(directoryFile, directory.privatePem, { mode: 0o600 });
writeFileSync(join(KEY_DIR, 'feed-public-key.txt'), feed.publicSpkiB64);
writeFileSync(join(KEY_DIR, 'directory-public-key.txt'), directory.publicSpkiB64);
writeFileSync(
  join(ROOT, 'src', 'feed', 'publicKey.ts'),
  `// Generated by \`npm run keys:generate\`. Ed25519 public keys (SPKI, base64) the browser verifies feeds with.\n` +
    `export const FEED_PUBLIC_KEY_SPKI_B64: string | null = '${feed.publicSpkiB64}'; // listings.json\n` +
    `export const DIRECTORY_PUBLIC_KEY_SPKI_B64: string | null = '${directory.publicSpkiB64}'; // pros.json\n`,
);
console.log(`Wrote private keys to ${KEY_DIR} and public keys to src/feed/publicKey.ts. Rebuild the site.`);
